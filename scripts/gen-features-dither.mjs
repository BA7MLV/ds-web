/**
 * 功能区四扇「窗口屏」的底图：有序抖动图案生成器。
 *
 * 管线与图元都在 `scripts/lib/dither.mjs`。这里只剩构图，四张各画一个符号。
 *
 * ── 墨色为什么是白的 ──
 * 「使用流程」那两张是白底压黑墨（`#1d1d1f`），深色下靠 `filter: invert(1)` 反相。
 * 这四张不一样：它们落在 `.lp-win__screen` 里，而那扇窗的屏幕是**深色**的
 * —— 四张真截图（home-chat / home-mindmap / home-quiz / home-anki）的主色都是
 * rgb(31,32,33)，`--fc-screen` 就是从这个值来的。
 * 所以这里直接写浅墨 `#e8e8ea`（比站点深色正文 --lp-text 低一档，
 * 与「使用流程」图案反相后的 #e2e2e0 是同一档重量），两套主题共用一份，不反相。
 *
 * ── 画布为什么是 452×282 ──
 * 1440 视口下实测：.lp-wrap 1080 → .lp-fcard 两列各 540 → .lp-fcard__stage
 * 内边距 44px → 右列内宽 452 → .lp-win 452×312.5 → .lp-win__screen 452×282.5。
 * 取整到 452×282（226×141 格），1px 就是 1px。
 *
 * 用法：node scripts/gen-features-dither.mjs
 * 产物：docs/public/feature-{chat,mindmap,quiz,anki}-dither.svg
 */
import {
  bake,
  canvas,
  circle,
  emit,
  paint,
  polyline,
  polygon,
  rampEdges,
  ring,
  rrect,
  seg,
  wrap,
} from './lib/dither.mjs'

/** 深色屏上的墨：见文件头「墨色为什么是白的」 */
const INK = '#e8e8ea'

/**
 * 四边溶解。
 * 「使用流程」那两张只化左边与顶边（右边、底边被卡片裁掉，要留硬边）；
 * 这四张的硬边界由窗口壳给，所以四边都化 —— 图案在屏里「浮」着。
 * 宽度按边长比例给：0.066 × 452 与 0.106 × 282 都约等于 30px，四边化掉的范围一样宽。
 */
const ramp = rampEdges({ left: 0.066, right: 0.066, top: 0.106, bottom: 0.106 })

/* ══════════════════════════════════════════════════════════════════════
 * ① 资料学习与智能对话 · 围绕你自己的材料学习
 *
 * 题眼是那根**引线** —— 对应 desc 里的「引用面板直接调取你的资料」：
 * 答案不是凭空来的，它指着材料里的某一段。
 *
 * 明度分配上有一条容易踩的坑：材料页那张「纸」是**底**，不是主体。
 * 第一版给了 0.26，出来是一整片均匀网点，把纸上的正文线全吞了 ——
 * 纸必须压到 0.15 一档，正文线（0.62）才浮得出来；高亮条（0.84）是纸上最重的东西。
 * 气泡同理：壳 0.36、里面的字 0.88。
 *
 * 气泡的纵向位置照材料页的重心（y=141）取，不照画布 —— 第一版让它贴着顶边，
 * 右下角空出一大块，整张图重心偏到左下角去了。
 * ══════════════════════════════════════════════════════════════════════ */
const chat = () => {
  const cv = canvas(452, 282)
  const f = cv.field

  paint(f, rrect(44, 44, 176, 194, 12), 0.15, cv)

  /* 正文六行，第 3 行的位置（y≈124）留给高亮条，不画字 */
  const rows = [68, 96, 124, 152, 180, 208]
  const widths = [108, 128, 96, 120, 132, 84]
  rows.forEach((y, i) => paint(f, rrect(68, y, widths[i], 9, 4.5), 0.62, cv))

  paint(f, rrect(58, 118, 142, 22, 6), 0.84, cv)

  paint(f, rrect(260, 95, 152, 92, 24), 0.36, cv)
  paint(f, polygon([[266, 142], [238, 158], [266, 166]]), 0.36, cv)
  paint(f, rrect(288, 118, 96, 8, 4), 0.88, cv)
  paint(f, rrect(288, 138, 72, 8, 4), 0.88, cv)
  paint(f, rrect(288, 158, 52, 8, 4), 0.88, cv)

  paint(f, seg(238, 158, 206, 132, 3.5), 0.7, cv)
  paint(f, circle(202, 129, 6), 0.88, cv)

  return wrap(cv, bake(f, cv, ramp), INK)
}

/* ══════════════════════════════════════════════════════════════════════
 * ② 知识导图 · 把知识整理成结构
 *
 * 题眼是**层级**：根 0.86 / 一级 0.62 / 二级 0.44，三级明度差本身就是「结构」。
 * 连线先画、节点压在上面 —— 反过来线会横穿节点，读成「被划掉」。
 * 连线取 4px（2 格）：2.5px 只有 1.25 格宽，阈值化后是一条断续的点线，
 * 看着像虚线而不是连线。
 * ══════════════════════════════════════════════════════════════════════ */
const mindmap = () => {
  const cv = canvas(452, 282)
  const f = cv.field

  /* 干：根到四个一级节点 */
  paint(f, seg(226, 126, 226, 72, 4), 0.48, cv)
  paint(f, seg(226, 156, 226, 210, 4), 0.48, cv)
  paint(f, seg(176, 141, 138, 141, 4), 0.48, cv)
  paint(f, seg(276, 141, 314, 141, 4), 0.48, cv)
  /* 枝：一级节点到二级节点，比干更淡一档 */
  paint(f, seg(102, 130, 68, 86, 4), 0.42, cv)
  paint(f, seg(102, 152, 68, 196, 4), 0.42, cv)
  paint(f, seg(350, 130, 384, 86, 4), 0.42, cv)
  paint(f, seg(350, 152, 384, 196, 4), 0.42, cv)

  paint(f, rrect(196, 50, 60, 22, 11), 0.62, cv)
  paint(f, rrect(196, 210, 60, 22, 11), 0.62, cv)
  paint(f, rrect(66, 130, 72, 22, 11), 0.62, cv)
  paint(f, rrect(314, 130, 72, 22, 11), 0.62, cv)
  paint(f, rrect(40, 70, 56, 16, 8), 0.44, cv)
  paint(f, rrect(40, 196, 56, 16, 8), 0.44, cv)
  paint(f, rrect(356, 70, 56, 16, 8), 0.44, cv)
  paint(f, rrect(356, 196, 56, 16, 8), 0.44, cv)
  /* 根最后画，盖住四根连线的接头 */
  paint(f, rrect(176, 126, 100, 30, 15), 0.86, cv)

  return wrap(cv, bake(f, cv, ramp), INK)
}

/* ══════════════════════════════════════════════════════════════════════
 * ③ 题目集与练习 · 把教材、试卷变成可练习的题库
 *
 * 题眼是**勾徽章 + 掌握度条** —— 对应 desc 的「自动判分，掌握度按知识点追踪」。
 * 左边卷子两道题：题号块 + 题干线 + 三个选项圆点，其中一个是实心选中的。
 * 与 ① 同一条教训：卷子是「底」，压到 0.14；题号块 0.82、题干 0.62、
 * 选项 0.5 / 选中 0.9 —— 纸一重，这些就全糊在纸里了。
 * ══════════════════════════════════════════════════════════════════════ */
const quiz = () => {
  const cv = canvas(452, 282)
  const f = cv.field

  paint(f, rrect(48, 38, 178, 206, 12), 0.14, cv)
  paint(f, rrect(74, 62, 92, 8, 4), 0.72, cv)

  paint(f, rrect(74, 92, 16, 16, 4), 0.82, cv)
  paint(f, rrect(100, 96, 104, 8, 4), 0.62, cv)
  paint(f, circle(100, 132, 5), 0.5, cv)
  paint(f, circle(126, 132, 5), 0.9, cv)
  paint(f, circle(152, 132, 5), 0.5, cv)

  paint(f, rrect(74, 170, 16, 16, 4), 0.82, cv)
  paint(f, rrect(100, 174, 86, 8, 4), 0.62, cv)
  paint(f, circle(100, 210, 5), 0.9, cv)
  paint(f, circle(126, 210, 5), 0.5, cv)
  paint(f, circle(152, 210, 5), 0.5, cv)

  paint(f, ring(360, 120, 42, 9), 0.74, cv)
  paint(f, seg(342, 122, 354, 134, 11), 0.86, cv)
  paint(f, seg(354, 134, 380, 102, 11), 0.86, cv)

  paint(f, rrect(272, 192, 144, 14, 7), 0.18, cv)
  paint(f, rrect(272, 192, 92, 14, 7), 0.72, cv)

  return wrap(cv, bake(f, cv, ramp), INK)
}

/* ══════════════════════════════════════════════════════════════════════
 * ④ Anki 智能制卡 · 把理解变成长期记忆
 *
 * 题眼是那条**遗忘曲线** —— 全页只有这一处出现曲线，辨识度靠它。
 * 上中三张错开的卡（0.1 / 0.17 / 0.25，越靠前越实），前排那张有问有答（0.9 / 0.72）；
 * 下方一条衰减锯齿：三次下坠、三次被复习拉回，拉回的位置各钉一个节点（0.8）。
 *
 * 卡片错开 22/20px：第一版只错开 18/16px，每张卡只露出 18px 一条边，三张糊成一块。
 * 卡面的档位也来回调过三遍 —— 0.34 时比曲线还重，整张图读起来是「一块噪点 + 一条线」；
 * 压到 0.25 之后曲线才重新是这张图里最亮的东西。**卡面是「底」，不是主体。**
 * ══════════════════════════════════════════════════════════════════════ */
const anki = () => {
  const cv = canvas(452, 282)
  const f = cv.field

  paint(f, rrect(118, 32, 168, 100, 12), 0.1, cv)
  paint(f, rrect(140, 52, 168, 100, 12), 0.17, cv)
  paint(f, rrect(162, 72, 168, 100, 12), 0.25, cv)
  paint(f, rrect(184, 94, 92, 10, 5), 0.9, cv)
  paint(f, rrect(184, 116, 118, 8, 4), 0.72, cv)
  paint(f, rrect(184, 138, 68, 8, 4), 0.72, cv)

  /*
   * 遗忘曲线：每次复习把记忆拉回峰值，之后按指数衰减。
   * 用「采样成点 + polyline」而不是写一条贝塞尔 —— 图元库里只有解析几何，
   * 多一个曲线原语不值当，而 50 来个点的折线在这个尺寸下看不出是折的。
   */
  const pts = [[56, 198]]
  const decay = (x0, x1, y0, y1) => {
    const n = 16
    const k = 1 - Math.exp(-3.2)
    for (let i = 1; i <= n; i += 1) {
      const t = i / n
      pts.push([x0 + (x1 - x0) * t, y0 + (y1 - y0) * ((1 - Math.exp(-3.2 * t)) / k)])
    }
  }
  decay(56, 148, 198, 250)
  pts.push([160, 200])
  decay(160, 252, 200, 250)
  pts.push([264, 202])
  decay(264, 356, 202, 250)
  pts.push([368, 204])
  paint(f, polyline(pts, 4), 0.62, cv)

  paint(f, circle(160, 200, 4.5), 0.8, cv)
  paint(f, circle(264, 202, 4.5), 0.8, cv)
  paint(f, circle(368, 204, 4.5), 0.8, cv)

  return wrap(cv, bake(f, cv, ramp), INK)
}

emit([
  ['feature-chat-dither.svg', chat()],
  ['feature-mindmap-dither.svg', mindmap()],
  ['feature-quiz-dither.svg', quiz()],
  ['feature-anki-dither.svg', anki()],
])
