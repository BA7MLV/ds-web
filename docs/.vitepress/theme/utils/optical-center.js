/**
 * 居中文案末尾是全角标点时的视觉校正判定。
 *
 * 全角标点的墨迹重心偏左下（句号在字框左下角、逗号在左下角），
 * 所以一行居中文字如果以标点收尾，它**看起来**会比容器中心偏左，
 * 字号越大越明显 —— 上方有图标之类的参照物时就尤其扎眼。
 * Apple 管这叫「标题居中视觉校正」，做法之一是给标题加 `padding-left: 0.5em`。
 *
 * 为什么要用脚本判、而不是在 CSS 里判：CSS 没有「取最后一个字符」的伪类，
 * 而我们也不能对每个标题手写一个修饰类 —— 文案在 i18n 表里，改一次就全对不上。
 * 这里只回答一个是非题，判定交给 CSS（见 custom.css 的 `.lp-optical`）。
 *
 * 为什么判定要剥掉换行符：短标题的断行是**写在文案里**的（`\n` + `white-space: pre-line`，
 * 见 HomePage.vue 的 .lp-hero__title）—— 中文可在任意字间断开，交给 text-wrap 去猜会
 * 把「就够了」拆到两行。所以「电脑上整理，\n手机上接着学。」这种标题的最后一个可见字符
 * 在句号，而字符串的最后一个字符是 `\n`。不剥掉就全都判不出来。
 * 只剥末尾的换行（`\s` 含换行与全角空格），中间的换行不动 —— 判的是末行收尾的那个字。
 */

/**
 * 会让行末视觉重心偏左的全角标点。
 * 取的是「墨迹在字框内偏左下」的那一类：句读号、终止号、结束括号。
 * 分隔号（、）和顿号位的中点（·）的偏心量很小，列进来是为了覆盖以它们收尾的短标语。
 */
const TAILING_FULLWIDTH_PUNCTUATION = /[。，、；：？！）」』】〉》…—·]$/u

/**
 * @param {unknown} text  i18n 表里取出的文案，通常是字符串
 * @returns {boolean}     该不该加 `.lp-optical`
 */
export const needsOpticalCenter = (text) =>
  typeof text === 'string' && TAILING_FULLWIDTH_PUNCTUATION.test(text.trimEnd())
